#!/usr/bin/env python3
"""Reference model for fn_047f54 (0x047f54) — fixed-point value normalizer.

Inputs (EAX:EDX register-ABI, 64-bit unsigned = EDX:EAX):
    lo = EAX (low 32), hi = EDX (high 32)
Output (EBX pointer): { uint32 lo; uint32 hi; uint16 field; }

Faithful model of the disasm (integer-only core):
    v      = (hi<<32|lo); v <<= 11
    eax    = v & 0xffffffff; edx = v >> 32
    ecx    = SAR(hi, 20)            (ARITHMETIC right shift, sign-extended)
    cx     = ecx & 0x7ff
    if cx == 0x7ff:                 # exponent overflow -> clamp to +inf
        cx = 0x7fff; if (edx|eax): edx |= 0x40000000
        edx |= 0x80000000
    elif cx != 0:                   # normalize: align bit31 to mantissa top
        cx += 0x3c00; edx |= 0x80000000
        while edx bit31 == 0: edx <<= 1 (+carry from eax); eax <<= 1; cx -= 1
    elif (edx|eax):                 # subnormal (cx == 0, value nonzero)
        cx = 0x3c01
        if edx == 0: swap(eax,edx); cx -= 0x20
        while edx bit31 == 0: edx <<= 1 (+carry from eax); eax <<= 1; cx -= 1
    else:                           # value == 0
        ecx = 0
    out[0]=eax; out[1]=edx; out[2] = (cx<<1) | bit31(ecx)
    # note: ecx is NOT re-clamped after `and cx,0x7ff`; its high 16 bits carry
    # the sign (for hi with bit31 set), so bit31(ecx)=1 for negative inputs.
"""
import ctypes
import random


def ref(lo, hi):
    ecx = hi
    v = (hi << 32) | lo
    v = (v << 11) & 0xffffffffffffffff
    eax = v & 0xffffffff
    edx = (v >> 32) & 0xffffffff
    ecx = (ctypes.c_int32(hi & 0xffffffff).value >> 20) & 0xffffffff   # SAR ecx,20
    cx = ecx & 0x7ff                      # and cx,0x7ff

    if cx == 0x7ff:                       # 0x47f85: overflow -> +inf
        cx = 0x7fff
        if edx != 0 or eax != 0:
            edx |= 0x40000000
        edx |= 0x80000000
    elif cx != 0:                         # 0x47f92: normalize
        cx = (cx + 0x3c00) & 0xffff
        edx |= 0x80000000
        while not (edx & 0x80000000):
            cf = (eax >> 31) & 1
            eax = (eax << 1) & 0xffffffff
            edx = ((edx << 1) + cf) & 0xffffffff
            cx = (cx - 1) & 0xffff
    elif edx != 0 or eax != 0:            # 0x47fab: subnormal
        cx = 0x3c01
        if edx == 0:
            eax, edx = edx, eax
            cx = (cx - 0x20) & 0xffff
        while not (edx & 0x80000000):
            cf = (eax >> 31) & 1
            eax = (eax << 1) & 0xffffffff
            edx = ((edx << 1) + cf) & 0xffffffff
            cx = (cx - 1) & 0xffff
    else:                                 # 0x47fb4: zero
        ecx = 0

    cf = (ecx >> 31) & 1
    out2 = ((cx << 1) | cf) & 0xffff
    return (eax, edx, out2)


if __name__ == "__main__":
    random.seed(0x047F54)
    cases = [
        (0, 0),
        (0x80000000, 0),
        (0, 0x40000000),
        (1, 0),
        (0x12345678, 0x23456789),
        (0, 0x7ff00000),          # cx = 0x7ff -> overflow
        (0, 0x7fe00000),          # cx = 0x7fe
        (0x55555555, 0x80000000), # cx = 0 -> subnormal (hi negative)
        (0, 1),
    ]
    for _ in range(2000):
        cases.append((random.getrandbits(32), random.getrandbits(32)))

    out = [
        "#ifndef FP_047F54_VECTORS_H",
        "#define FP_047F54_VECTORS_H",
        "",
        "/* Generated by scratch/fp_047f54_ref.py -- do not edit. */",
        "typedef struct {",
        "    unsigned int in_lo;   /* EAX */",
        "    unsigned int in_hi;   /* EDX */",
        "    struct { unsigned int lo; unsigned int hi; unsigned short field; } exp;",
        "} fp_047f54_vec_t;",
        "",
        "static const fp_047f54_vec_t fp_047f54_vectors[] = {",
    ]
    for (lo, hi) in cases:
        e, d, f2 = ref(lo, hi)
        out.append(
            f"    {{0x{lo:08x},0x{hi:08x},{{0x{e:08x},0x{d:08x},0x{f2:04x}}}}},"
        )
    out.append("};")
    out.append("")
    out.append(f"#define FP_047F54_VECTORS_N ({len(cases)})")
    out.append("")
    out.append("#endif /* FP_047F54_VECTORS_H */")
    with open("port/test/vectors/fp_047f54_vectors.h", "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"// wrote {len(cases)} vectors", flush=True)
