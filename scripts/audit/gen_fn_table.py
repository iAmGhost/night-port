#!/usr/bin/env python3
"""Generate the per-function entry-census table (docs/120).

Coverage-guided fuzzing needs a coverage signal keyed to the shipped binary. The port's function names ARE
guest addresses, so the census is keyed to those names: this script lists every externally linkable
definition in the port's f-layer translation units and emits

  port/src/gen/fn_table.c   -- void *g_fn_addr[N] + const char *g_fn_name[N], sorted by address

`-finstrument-functions` then turns every call into an index lookup (bsearch over g_fn_addr), which is what
scripts/rig/fuzz.py uses as its coverage vector.
"""
import re
import sys

RE_SRC = "src/f/f.c src/f/fx_04794a.c src/f/f047a50.c src/sys/sys.c src/cd/cd_iso.c src/app/keymap.c"
DEF = re.compile(r"^(?:__attribute__\(\([^)]*\)\)\s*)?([A-Za-z_][A-Za-z0-9_]*\s+\**|[A-Za-z_][A-Za-z0-9_]*\s*\**)?"
                 r"\s*([A-Za-z_][A-Za-z0-9_]*)\s*\(([^;{]*)\)\s*\{", re.M)

def main():
    import re, os, sys
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import port_src
    defined, _calls = port_src.functions()
    src = "\n".join(t for _n, t in port_src._files())
    static = set(re.findall(r"\bstatic\s+[A-Za-z_][A-Za-z0-9_\s*]*?([A-Za-z_][A-Za-z0-9_]*)\s*\(", src))
    names = sorted(n for n in defined if n != "main" and n not in static
                   and not n.startswith("__toplevel__"))
    lines = [
        "/* Generated by scripts/audit/gen_fn_table.py -- do not edit.",
        "   Per-function entry census table: g_fn_addr[i] is the address of the function whose shipped name is",
        "   g_fn_name[i] (the name IS the guest address). Sorted by address for the bsearch in rig_census.c. */",
        "#include <stddef.h>",
        "",
        "/* Taking an address does not depend on the prototype, so one uniform extern is enough. */",
    ]
    for n in names:
        lines.append(f"extern void {n}(void);")
    lines += ["", f"void *const g_fn_addr[{len(names)}] = {{"]
    for i in range(0, len(names), 5):
        lines.append("    " + ", ".join(f"(void *)&{n}" for n in names[i:i + 5]) + ",")
    lines += ["};", "", f"const char *const g_fn_name[{len(names)}] = {{"]
    for i in range(0, len(names), 4):
        lines.append("    " + ", ".join(f'"{n}"' for n in names[i:i + 4]) + ",")
    lines += ["};", "", f"const unsigned g_fn_count = {len(names)};", ""]

    # Addresses are link-time, so the table stays in name order here and rig_census.c sorts a permutation
    # of indices by address once at startup (never sort the two arrays independently).
    import os
    os.makedirs("port/src/gen", exist_ok=True)
    open("port/src/gen/fn_table.c", "w").write("\n".join(lines) + "\n")
    open("port/src/gen/fn_table.h", "w").write(
        "#pragma once\n#include <stddef.h>\n"
        "extern void *const g_fn_addr[];\n"
        "extern const char *const g_fn_name[];\n"
        "extern const unsigned g_fn_count;\n")
    print(f"port/src/gen/fn_table.c: {len(names)} functions")

if __name__ == "__main__":
    main()
