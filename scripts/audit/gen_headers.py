#!/usr/bin/env python3
"""Turn the Ghidra export into the artifacts the other audits and the state oracle consume.

gen/ds_join.json  - one row per DS cell the guest touches: guest symbol + size + type,
                    read/write counts, write sites, image-initial value, port name(s)/type.
gen/ds_symbols.h  - C table for the port's state-dump machinery (address, size, id).
gen/fn_census.h   - C table of every shipped function entry, for the coverage census.

Run after NightExport.java has refreshed the JSON inputs.
"""
import json
import os

import ghidra_db
import port_src
import static_audit

HERE = os.path.dirname(os.path.abspath(__file__))
GEN = os.path.join(HERE, "gen")


def width_from_access(acc_w, addr):
    """The operand width(s) the guest actually moves through this address, as recorded text.

    This is an ACCESS width, not a symbol span: `MOV EAX, dword ptr [0x51b60]` proves a dword is read at
    the head of a 256-byte table, it does not prove the table is 4 bytes. So it never replaces
    defined_data's size in the dump table -- it is carried alongside it, and static_audit c9 uses it to
    catch a port global whose element type is a different width from every shipped access at that cell.
    """
    ws = acc_w.get(addr)
    if not ws:
        return None
    if isinstance(ws, dict):
        direct = ws.get("direct") or set()
        return max(direct) if direct else None
    return max(ws)


def main():
    os.makedirs(GEN, exist_ok=True)
    db = ghidra_db.Db()
    pmap = static_audit.port_global_map()
    reads, writes = db.ds_read_sites(), db.ds_write_sites()
    dd_by_addr = {int(d["addr"], 16): d for d in db.ds_data()}
    # docs/132 §3: 66 of the 283 rig cells had no shipped width because Ghidra never *defined* a data
    # symbol there. The disassembly still states the operand size, so recover the width from the accesses.
    acc_w = db.ds_access_widths()
    rows = []
    for addr in sorted(set(db.ds_dir_counts()) | set(dd_by_addr) | set(pmap)):
        d = dd_by_addr.get(addr)
        decls = pmap.get(addr, [])
        img = db.image_u32(addr) if db.in_image(addr) else None
        gsz = d["size"] if d and d.get("size") else None
        rows.append({
            "ds": addr,
            "guest_symbol": d["label"] if d else None,
            "guest_type": d["type"] if d else None,
            "guest_size": gsz,
            "guest_access_width": width_from_access(acc_w, addr),
            "guest_access_widths_direct": sorted(acc_w.get(addr, {}).get("direct", [])),
            "guest_access_widths_based": sorted(acc_w.get(addr, {}).get("based", [])),
            "reads": len(reads.get(addr, [])),
            "writes": len(writes.get(addr, [])),
            "write_sites": [f"{w[1]}@{w[0]} {w[2]} {w[3]}" for w in writes.get(addr, [])][:6],
            "image_u32": img,
            "port_names": sorted({x["name"] for x in decls}),
            "port_types": sorted({x["ctype"] for x in decls}),
        })
    with open(os.path.join(GEN, "ds_join.json"), "w") as f:
        json.dump(rows, f, indent=1)

    # C tables (dump list = cells the guest actually touches, ordered by activity)
    touched = [r for r in rows if r["reads"] or r["writes"]]
    with open(os.path.join(GEN, "ds_symbols.h"), "w") as f:
        f.write("/* generated by scripts/audit/gen_headers.py from the NIGHT.EXE Ghidra export; do not edit */\n")
        f.write("#ifndef NIGHT_DS_SYMBOLS_H\n#define NIGHT_DS_SYMBOLS_H\n#include <stdint.h>\n\n")
        f.write("struct ds_symbol { uint32_t addr; uint16_t size; int16_t id; };\n")
        f.write(f"static const struct ds_symbol g_ds_symbols[] = /* {len(touched)} */ {{\n")
        for i, r in enumerate(touched):
            f.write(f'    {{0x{r["ds"]:05x}, {r["guest_size"] or 4}, {i}}}, /* {r["guest_symbol"] or "-"} '
                    f'R{r["reads"]} W{r["writes"]} */\n')
        f.write("};\n\nstatic const char *const g_ds_symbol_names[] = {\n")
        for r in touched:
            nm = (r["port_names"][0] if r["port_names"] else r["guest_symbol"] or "?")
            f.write(f'    "{nm}",\n')
        f.write("};\n\n#endif\n")

    # a mask over the cells the guest actually touches: the state digest is computed over this, so
    # frame-local stack traffic and untouched padding cannot masquerade as "state changed".
    mask = bytearray(ghidra_db.DS_HI - ghidra_db.DS_LO)
    for r in rows:
        if r["reads"] or r["writes"]:
            sz = r["guest_size"] or 4
            for k in range(sz):
                a = r["ds"] - 0x50000 + k
                if 0 <= a < len(mask):
                    mask[a] = 1
    with open(os.path.join(GEN, "ds_mask.bin"), "wb") as f:
        f.write(bytes(mask))

    # rig_table.h: the port's state-dump table. Every port global that claims a DS-group address
    # becomes a recordable cell with BOTH widths (the size the guest's accesses imply and the size the
    # port's declaration implies) -- the two disagreeing is a finding (docs/94 family), not something to
    # smooth over. Cells whose port comment claims an address outside the DS group are listed in
    # gen/rig_unmapped.json instead: they cannot be read through the calibrated DS physical base, and
    # silently dumping them would invent an oracle.
    cells, unmapped, dup_claims = [], [], []
    for addr in sorted(pmap):
        # Several port globals can claim one DS cell. Pick the one whose shape could BE the cell (a
        # pointer slot beats an `int`), and keep the rest as a finding: `g_dat_53c7c_null_warned` is a
        # port-local debug flag that only *looks* like DAT_00053c7c because of its name, and taking it
        # alphabetically replaced the player-entity pointer in the rig table.
        decls = sorted(pmap[addr], key=lambda d: (-(8 if d["ptr"] else d["type_size"] * max(1, d["elems"])),
                                                  d["name"]))
        d = decls[0]
        if len(decls) > 1:
            dup_claims.append({"ds": addr, "chosen": d["name"],
                               "claims": [{"name": x["name"], "ctype": x["ctype"], "ptr": 1 if x["ptr"] else 0,
                                           "file": x["file"], "line": x["line"], "ds_from_name":
                                           bool(port_src.NAME_ADDR.search(x["name"]))} for x in decls]})
        g = dd_by_addr.get(addr)
        gsz = (g["size"] if g and g.get("size") else 0)
        aw = width_from_access(acc_w, addr)
        # a pointer field occupies 8 host bytes but 4 guest bytes: keep both, the differ reports the
        # pair rather than guessing which side is wrong.
        slot = 8 if d["ptr"] else d["type_size"]
        hsz = max(1, min(256, d["elems"] * slot)) if slot else 0
        rec = {"ds": addr, "name": d["name"], "ctype": d["ctype"], "guest_size": gsz,
               "guest_access_width": aw, "elem_size": slot,
               "host_size": hsz, "ptr": 1 if d["ptr"] else 0, "dupes": len(decls) - 1}
        (cells if ghidra_db.DS_LO <= addr < ghidra_db.DS_HI else unmapped).append(rec)
    with open(os.path.join(GEN, "port_dup_claims.json"), "w") as f:
        json.dump(dup_claims, f, indent=1)

    with open(os.path.join(HERE, "..", "..", "port", "src", "f", "rig_table.h"), "w") as f:
        f.write("/* generated by scripts/audit/gen_headers.py from the NIGHT.EXE Ghidra export; do not edit.\n"
                "   included at the end of f.c so the file-scope statics are visible; see f/rig_cells.h */\n")
        f.write("#include \"rig_cells.h\"\n\n")
        f.write(f"static const struct rig_cell g_rig_cells[] = /* {len(cells)} */ {{\n")
        for c in cells:
            f.write(f'    {{0x{c["ds"]:05x}, {c["guest_size"]}, {c["host_size"]}, {c["ptr"]}, '
                    f'&{c["name"]}, "{c["name"]}"}},\n')
        f.write("};\n\nint rig_cell_count(void) { return (int)(sizeof g_rig_cells / sizeof g_rig_cells[0]); }\n")
        f.write("const struct rig_cell *rig_cell_at(int i) { return &g_rig_cells[i]; }\n")
    fcp = os.path.join(HERE, "..", "..", "port", "src", "f", "f.c")
    src = open(fcp).read()
    if "rig_table.h" not in src:
        if not src.endswith("\n"):
            src += "\n"
        src += ('\n/* the rig\'s state-dump table (generated; see src/f/rig_cells.h) */\n'
                '#include "rig_table.h"\n')
        open(fcp, "w").write(src)
    json.dump(cells, open(os.path.join(GEN, "rig_cells.json"), "w"), indent=1)
    json.dump(unmapped, open(os.path.join(GEN, "rig_unmapped.json"), "w"), indent=1)

    fns = sorted(db.functions, key=lambda x: int(x["entry"], 16))
    with open(os.path.join(GEN, "fn_census.h"), "w") as f:
        f.write("/* generated: every shipped function entry (coverage census); do not edit */\n")
        f.write("#ifndef NIGHT_FN_CENSUS_H\n#define NIGHT_FN_CENSUS_H\n#include <stdint.h>\n\n")
        f.write(f"#define NIGHT_FN_COUNT {len(fns)}\n")
        f.write("static const uint32_t g_fn_entries[] = {\n")
        for x in fns:
            f.write(f'    0x{int(x["entry"], 16):05x}, /* {x["name"]} */\n')
        f.write("};\n\n#endif\n")

    port_defs, _ = port_src.functions()
    guest_names = {x["name"] for x in fns}
    port_fn = {n for n in port_defs if n.startswith("fn_")}
    info = {
        "guest_defined_data_rows": len(db.defined_data),
        "guest_ds_rows": len(db.ds_data()),
        "ds_join_rows": len(rows),
        "ds_cells_touched": len(touched),
        "guest_functions": len(fns),
        "port_fn_names": len(port_fn),
        "guest_fn_without_port_fn": len(guest_names - port_fn),
        "port_fn_without_guest_fn": len(port_fn - guest_names),
    }
    with open(os.path.join(GEN, "gen_info.json"), "w") as f:
        json.dump(info, f, indent=1)
    print(json.dumps(info, indent=1))


if __name__ == "__main__":
    main()
