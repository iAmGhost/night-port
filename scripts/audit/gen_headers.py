#!/usr/bin/env python3
"""Turn the Ghidra export into the artifacts the other audits and the state oracle consume.

gen/ds_join.json  - one row per DS cell the guest touches: guest symbol + size + type,
                    read/write counts, write sites, image-initial value, port name(s)/type.
gen/ds_symbols.h  - C table for the port's state-dump machinery (address, size, id).
gen/fn_census.h   - C table of every shipped function entry, for the coverage census.

Run after NightExport.java has refreshed the JSON inputs.
"""
import json
import os

import ghidra_db
import port_src
import static_audit

HERE = os.path.dirname(os.path.abspath(__file__))
GEN = os.path.join(HERE, "gen")


def main():
    os.makedirs(GEN, exist_ok=True)
    db = ghidra_db.Db()
    pmap = static_audit.port_global_map()
    reads, writes = db.ds_read_sites(), db.ds_write_sites()
    dd_by_addr = {int(d["addr"], 16): d for d in db.ds_data()}

    rows = []
    for addr in sorted(set(db.ds_dir_counts()) | set(dd_by_addr) | set(pmap)):
        d = dd_by_addr.get(addr)
        decls = pmap.get(addr, [])
        img = db.image_u32(addr) if db.in_image(addr) else None
        rows.append({
            "ds": addr,
            "guest_symbol": d["label"] if d else None,
            "guest_type": d["type"] if d else None,
            "guest_size": d["size"] if d else None,
            "reads": len(reads.get(addr, [])),
            "writes": len(writes.get(addr, [])),
            "write_sites": [f"{w[1]}@{w[0]} {w[2]} {w[3]}" for w in writes.get(addr, [])][:6],
            "image_u32": img,
            "port_names": sorted({x["name"] for x in decls}),
            "port_types": sorted({x["ctype"] for x in decls}),
        })
    with open(os.path.join(GEN, "ds_join.json"), "w") as f:
        json.dump(rows, f, indent=1)

    # C tables (dump list = cells the guest actually touches, ordered by activity)
    touched = [r for r in rows if r["reads"] or r["writes"]]
    with open(os.path.join(GEN, "ds_symbols.h"), "w") as f:
        f.write("/* generated by scripts/audit/gen_headers.py from the NIGHT.EXE Ghidra export; do not edit */\n")
        f.write("#ifndef NIGHT_DS_SYMBOLS_H\n#define NIGHT_DS_SYMBOLS_H\n#include <stdint.h>\n\n")
        f.write("struct ds_symbol { uint32_t addr; uint16_t size; int16_t id; };\n")
        f.write(f"static const struct ds_symbol g_ds_symbols[] = /* {len(touched)} */ {{\n")
        for i, r in enumerate(touched):
            f.write(f'    {{0x{r["ds"]:05x}, {r["guest_size"] or 4}, {i}}}, /* {r["guest_symbol"] or "-"} '
                    f'R{r["reads"]} W{r["writes"]} */\n')
        f.write("};\n\nstatic const char *const g_ds_symbol_names[] = {\n")
        for r in touched:
            nm = (r["port_names"][0] if r["port_names"] else r["guest_symbol"] or "?")
            f.write(f'    "{nm}",\n')
        f.write("};\n\n#endif\n")

    fns = sorted(db.functions, key=lambda x: int(x["entry"], 16))
    with open(os.path.join(GEN, "fn_census.h"), "w") as f:
        f.write("/* generated: every shipped function entry (coverage census); do not edit */\n")
        f.write("#ifndef NIGHT_FN_CENSUS_H\n#define NIGHT_FN_CENSUS_H\n#include <stdint.h>\n\n")
        f.write(f"#define NIGHT_FN_COUNT {len(fns)}\n")
        f.write("static const uint32_t g_fn_entries[] = {\n")
        for x in fns:
            f.write(f'    0x{int(x["entry"], 16):05x}, /* {x["name"]} */\n')
        f.write("};\n\n#endif\n")

    port_defs, _ = port_src.functions()
    guest_names = {x["name"] for x in fns}
    port_fn = {n for n in port_defs if n.startswith("fn_")}
    info = {
        "guest_defined_data_rows": len(db.defined_data),
        "guest_ds_rows": len(db.ds_data()),
        "ds_join_rows": len(rows),
        "ds_cells_touched": len(touched),
        "guest_functions": len(fns),
        "port_fn_names": len(port_fn),
        "guest_fn_without_port_fn": len(guest_names - port_fn),
        "port_fn_without_guest_fn": len(port_fn - guest_names),
    }
    with open(os.path.join(GEN, "gen_info.json"), "w") as f:
        json.dump(info, f, indent=1)
    print(json.dumps(info, indent=1))


if __name__ == "__main__":
    main()
