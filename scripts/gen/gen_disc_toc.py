#!/usr/bin/env python3
"""Generate src/gen/disc_toc.h -- the compiled-in disc geometry of TG_NIGHT.

WHY THIS EXISTS.  src/cd/cd_iso.c reads the disc layout out of TG_NIGHT.CUE at run time, and the game's
disc-present gate (fn_010c3e) polls that TOC until it sees 15 tracks whose track-3-minus-track-2 gap is
0xc51.  That made the CUE a start-up requirement: with only the extracted resources and no disc data of
any kind, the gate loops on "cdinsert.pcx" and the game never begins.  This header carries the same
geometry the CUE states, so the gate passes, the game runs, and every CD-DA read is refused -- no music,
no fake bytes (docs/455).

THE ONE NUMBER THE CUE DOES NOT CARRY is where the last track ends: a CUE sheet states INDEX 01 per
track and nothing after the last one, so the disc's total comes from the image's sector count (+150 for
the PREGAP) or from the last trackNN.bin.  This generator reads TG_NIGHT.IMG when it can find it and
takes the total from there; with no image it refuses to guess and says so.

BUILDING NEVER NEEDS ANY OF THIS: the header is checked in.  Only re-running this script does.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "src" / "gen" / "disc_toc.h"
SECTOR = 2352
PREGAP = 150


def first_by_suffix(dirs, suffixes):
    """The first file with one of these suffixes (lower-cased), by directory then by name.

    Same rule scripts/extract_disc.py uses, so the two tools cannot disagree about which disc a
    directory holds -- and the suffix is compared lower-cased because a CUE sheet is often named .CUE.
    """
    for d in dirs:
        if not d.is_dir():
            continue
        for suf in suffixes:
            for c in sorted(p for p in d.iterdir() if p.is_file() and p.suffix.lower() == suf):
                return c
    return None


def parse_cue(path: Path):
    """(tracks, pregap, data_file) -- tracks = [(number, mode, disc_lba)], in disc order.

    Only what the geometry needs: INDEX 01 per track, PREGAP, and the FILE line for the image name.
    Disc LBAs include the pregap, which is how MSCDEX (and therefore the game) numbers sectors.
    """
    tracks, pregap, data_file = [], 0, None
    num, mode, first = 0, "", None
    for line in path.read_text(errors="replace").splitlines():
        m = re.match(r'\s*FILE\s+"([^"]*)"\s+(\S+)', line)
        if m:
            data_file = m.group(1)
            continue
        m = re.match(r"\s*TRACK\s+(\d+)\s+(\S+)", line)
        if m:
            if num and first is not None:
                tracks.append((num, mode, first + pregap))
            num, mode, first = int(m.group(1)), m.group(2), None
            continue
        m = re.match(r"\s*PREGAP\s+(\d+):(\d+):(\d+)", line)
        if m:                       # MSF -> sectors: the CUE's PREGAP 00:02:00 is 150
            pregap += int(m[1]) * 4500 + int(m[2]) * 75 + int(m[3])
            continue
        m = re.match(r"\s*INDEX\s+(\d+)\s+(\d+):(\d+):(\d+)", line)
        if m and int(m[1]) == 1 and first is None:
            first = int(m[2]) * 4500 + int(m[3]) * 75 + int(m[4])
    if num and first is not None:
        tracks.append((num, mode, first + pregap))
    return tracks, pregap, data_file


def main() -> int:
    cue = Path(sys.argv[1]) if len(sys.argv) > 1 else None
    if cue is None:
        cue = first_by_suffix([Path.cwd(), REPO, REPO / "NIGHT"], [".cue"])
    if cue is None or not Path(cue).exists():
        sys.exit("no .cue to read from: pass one as an argument")
    tracks, pregap, data_file = parse_cue(Path(cue))
    if not tracks:
        sys.exit(f"{cue} lists no tracks")

    img = Path(sys.argv[2]) if len(sys.argv) > 2 else None
    if img is None:
        img = Path(cue).parent / data_file if data_file else None
        if img is None or not img.exists():
            img = first_by_suffix([Path(cue).parent, Path.cwd(), REPO, REPO / "NIGHT"], [".img", ".bin"])
    if img is None or not Path(img).exists():
        sys.exit(f"no disc image beside {cue}: the total sector count (the end of the last track) cannot be "
                 f"guessed -- pass the image as an argument")
    total = Path(img).stat().st_size // SECTOR + pregap

    audio = [t for t in tracks if t[1].startswith("AUDIO")]
    gap = tracks[2][2] - tracks[1][2] if len(tracks) > 2 else 0
    img_sectors = Path(img).stat().st_size // SECTOR
    tracks_n = len(tracks)
    n = len(tracks)
    head = [
        "#pragma once",
        "#include <stdint.h>",
        "/* disc_toc.h -- GENERATED by scripts/gen/gen_disc_toc.py from " + Path(cue).name + " (docs/455).",
        " *",
        f" * The disc geometry that lets the port boot from its resources alone: src/cd/cd_iso.c falls back",
        f" * to this table when TG_NIGHT.CUE is not there to parse, so the disc-present gate fn_010c3e sees",
        f" * the {n} tracks and the 0x{gap:x} gap it polls for, and the game begins.  There is no byte source",
        f" * behind it, so every cd_iso_read_audio() is refused and the game runs silent -- silence here is",
        f" * the port refusing to invent samples, not a decoded second of nothing.",
        " *",
        f" * {n} tracks ({len(audio)} audio), track 01 at disc LBA {tracks[0][2]}, total {total} sectors =",
        f" * {Path(img).name} ({img_sectors} image sectors + the {pregap}-sector PREGAP the CUE states).",
        f" * Building never needs the disc; only re-running the generator does, and only for this total.",
        " */",
        f"#define DISC_TOC_TRACKS {n}u",
        f"#define DISC_TOC_FIRST {tracks[0][0]}u",
        f"#define DISC_TOC_LAST {tracks[-1][0]}u",
        f"#define DISC_TOC_TOTAL_SECTORS {total}u",
        f"#define DISC_TOC_PREGAP {pregap}u",
        f"static const uint8_t  g_disc_toc_track[{n}] = {{ {', '.join(str(t[0]) for t in tracks)} }};",
        f"static const uint32_t g_disc_toc_lba[{n}] = {{ {', '.join(str(t[2]) for t in tracks)} }};",
        f"static const uint8_t  g_disc_toc_audio[{n}] = {{ "
        f"{', '.join('1' if t[1].startswith('AUDIO') else '0' for t in tracks)} }};",
        "",
    ]
    OUT.write_text("\n".join(head) + "\n")
    print(f"wrote {OUT}: {len(tracks)} tracks, total {total} sectors (cue {cue}, img {img})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
