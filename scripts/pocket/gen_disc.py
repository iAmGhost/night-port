#!/usr/bin/env python3
"""Generate pocket/src/night/disc_table.h — the TG_NIGHT disc map, compiled in.

Why compiled in: the SDL host learns the disc layout by parsing NIGHT/TG_NIGHT.CUE and
stat()ing TG_NIGHT.IMG at run time (src/cd/cd_iso.c).  On the Pocket there is no CUE file and
no single IMG file — the audio tracks ship as one data slot each — so the layout the disc gate
needs (fn_010927's 7-byte header, fn_107b9's 5-byte TOC records, the 0xc51 gate on records 1/2)
is baked into the binary from the same CUE at build time.  The numbers are identical to what
cd_iso_open() computes: LBA = MSF frames from disc start + accumulated PREGAP, IMG sectors =
disc frames - pregap, lead-out = total + 150.

Run:  python3 scripts/pocket/gen_disc.py      (also `make -C pocket/src/night disc`)
"""
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CUE = REPO / "NIGHT" / "TG_NIGHT.CUE"
IMG = REPO / "NIGHT" / "TG_NIGHT.IMG"
OUT = REPO / "pocket" / "src" / "night" / "disc_table.h"

SECTOR = 2352


def msf_to_frames(t: str) -> int:
    m, s, f = (int(x) for x in t.split(":"))
    return m * 4500 + s * 75 + f


def main():
    if not CUE.is_file():
        sys.exit(f"missing {CUE}")
    img_sectors = IMG.stat().st_size // SECTOR if IMG.is_file() else None

    tracks = []            # (track, lba) in disc order, exactly as cd_iso_open builds it
    pregap = 0
    cur = 0
    first_frame = None
    first_track = last_track = 0
    for line in CUE.read_text().splitlines():
        line = line.strip()
        if line.startswith("TRACK "):
            _, tn, _mode = line.split()
            if cur and first_frame is not None:
                tracks.append((cur, msf_to_frames(first_frame) + pregap))
            cur = int(tn)
            first_frame = None
            if not first_track:
                first_track = cur
            last_track = cur
        elif line.startswith("PREGAP "):
            pregap += msf_to_frames(line.split()[1])
        elif line.startswith("INDEX "):
            parts = line.split()
            if int(parts[1]) == 1 and first_frame is None:
                first_frame = parts[2]
    if cur and first_frame is not None:
        tracks.append((cur, msf_to_frames(first_frame) + pregap))

    if not tracks:
        sys.exit("no tracks parsed")

    total = img_sectors + pregap if img_sectors is not None else None
    leadout = None
    if total is not None:
        addr = total + 150
        leadout = (addr // 4500, (addr // 75) % 60, addr % 75)   # (m, s, f)

    audio = [t for t, _ in tracks if t != tracks[0][0]]
    lines = [
        "/* disc_table.h -- GENERATED by scripts/pocket/gen_disc.py from NIGHT/TG_NIGHT.CUE."
        " Do not edit.",
        " *",
        " * Same arithmetic as src/cd/cd_iso.c: LBA = MSF frames from disc start + accumulated PREGAP;",
        " * the .IMG carries no pregap, so disc LBA <-> file sector is exactly -150 here.",
        " */",
        "#ifndef NIGHT_DISC_TABLE_H",
        "#define NIGHT_DISC_TABLE_H",
        "",
        f"#define DISC_FIRST_TRACK {first_track}",
        f"#define DISC_LAST_TRACK  {last_track}",
        f"#define DISC_TRACK_COUNT {len(tracks)}",
        f"#define DISC_PREGAP_FRAMES {pregap}",
    ]
    if total is not None:
        lines += [
            f"#define DISC_IMG_SECTORS {img_sectors}u   /* TG_NIGHT.IMG size / 2352 */",
            f"#define DISC_TOTAL_SECTORS {total}u       /* img sectors + pregap */",
            f"#define DISC_LEADOUT_M {leadout[0]}u",
            f"#define DISC_LEADOUT_S {leadout[1]}u",
            f"#define DISC_LEADOUT_F {leadout[2]}u",
        ]
    else:
        lines.append("/* TG_NIGHT.IMG not present at generation time: total sectors unknown */")
    lines += [
        "",
        "typedef struct disc_track { unsigned track; unsigned lba; char audio; } disc_track_t;",
        "",
        "static const disc_track_t g_disc_tracks[DISC_TRACK_COUNT] = {",
    ]
    for tr, lba in tracks:
        lines.append(f"    {{ {tr}, {lba}u, {(1 if tr != tracks[0][0] else 0)} }},")
    lines += ["};", "", "#endif /* NIGHT_DISC_TABLE_H */", ""]
    OUT.write_text("\n".join(lines))

    # The disc-present gate fn_010c3e compares the TOC dwords of records 1 and 2 -- the first two
    # AUDIO tracks -- and wants 0xc51 = 3153 sectors.
    gate = tracks[2][1] - tracks[1][1] if len(tracks) > 2 else 0
    print(f"wrote {OUT}: {len(tracks)} tracks, first={first_track} last={last_track}, "
          f"pregap={pregap}, total={total}, track3-track2 gap={gate} (gate wants 3153)")


if __name__ == "__main__":
    main()
