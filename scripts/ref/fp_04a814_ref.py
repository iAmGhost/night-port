#!/usr/bin/env python3
# Reference for fn_04a814 (orig 0x04a814): linear upper-bound scan over the
# 8-byte {hi,lo} powers-of-10 table at 0x04a928, returning an EAX counter.
#
# Table (22 entries, 0x04a928..0x04a9d0):
#   [0]=0, [1]=10^0, [2]=10^1, ... [20]=10^19, [21]=UINT64_MAX (sentinel)
#
# x86 (0x04a814):
#   PUSH EDI; PUSH ECX
#   CALL 0x04a923         ; EDI := 0x04a928 (table base), EAX unchanged (=start)
#   INC EAX               ; EAX = start+1
#   LEA EDI,[EDI+EAX*8]   ; e = start+1
#   ECX=[EDX] (lo); EDX=[EDX+4] (hi)  ; key = (hi<<32)|lo
#   SUB EAX,EAX           ; cnt = 0
#   forward:
#     CMP EDX,[EDI]; JNZ ->; CMP ECX,[EDI+4]; JC ->backward
#     i.e. advance while key >= entry; break to backward when key < entry
#     ADD EDI,8; INC EAX
#   backward:
#     SUB EDI,8; CMP...; JNC ->break   ; step back while entry > key
#     SUB EDI,8; DEC EAX
#   return EAX (= cnt)
#
# The 64-bit compare "key < entry" = (hi < ehi) || (hi==ehi && lo < elo).

U64 = (1 << 64) - 1
TBL = [0] + [10 ** i for i in range(0, 20)] + [U64]
assert len(TBL) == 22
assert TBL[0] == 0
assert TBL[1] == 1
assert TBL[2] == 10
assert TBL[19] == 10 ** 18
assert TBL[20] == 10 ** 19
assert TBL[21] == U64

def key_lt(hi, lo, ent):
    ehi = (ent >> 32) & 0xffffffff
    elo = ent & 0xffffffff
    return (hi < ehi) or (hi == ehi and lo < elo)

def scan(start, hi, lo):
    # e is the table index; cnt is the EAX counter
    e = (start + 1) & 0xffffffff
    cnt = 0
    # forward: advance while key >= entry
    while True:
        if key_lt(hi, lo, TBL[e]):
            break
        e = (e + 1) & 0xffffffff
        cnt += 1
    # backward: step back while entry > key
    while True:
        e = (e - 1) & 0xffffffff
        if not key_lt(hi, lo, TBL[e]):
            break
        e = (e - 1) & 0xffffffff
        cnt -= 1
    return cnt

def main():
    import random
    random.seed(0x814)
    vecs = []
    # deterministic power-of-10 keys at various start positions
    for k in range(0, 20):
        key = 10 ** k
        hi = (key >> 32) & 0xffffffff
        lo = key & 0xffffffff
        for start in range(0, min(k + 1, 20)):
            vecs.append((hi, lo, start, scan(start, hi, lo)))
    # random keys (in-range, < 10^19 so the scan stays within the real table)
    for _ in range(3000):
        key = random.randrange(0, 10 ** 19 + 1)
        hi = (key >> 32) & 0xffffffff
        lo = key & 0xffffffff
        start = random.randrange(0, 20)
        vecs.append((hi, lo, start, scan(start, hi, lo)))
    # exact sentinel boundary
    hi, lo = 0xffffffff, 0xfffffffe
    vecs.append((hi, lo, 0, scan(0, hi, lo)))
    vecs.append((0, 0, 0, scan(0, 0, 0)))          # key=0
    vecs.append((0, 1, 0, scan(0, 0, 1)))          # key=1

    with open("test/vectors/fp_04a814_vectors.h", "w") as f:
        f.write("/* auto-generated by scripts/ref/fp_04a814_ref.py -- do not edit */\n")
        f.write("#ifndef FP_04A814_VECTORS_H\n#define FP_04A814_VECTORS_H\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write("static const uint32_t V814[%d][4] = {\n" % len(vecs))
        for i, (hi, lo, st, res) in enumerate(vecs):
            f.write("  {0x%08u, 0x%08u, %u, %d}%s\n" % (hi, lo, st, res,
                     "," if i + 1 < len(vecs) else ""))
        f.write("};\n")
        f.write("#define NV814 %d\n\n" % len(vecs))
        f.write("#endif\n")
    # print a few sanity cases
    print("vectors:", len(vecs))
    for (hi, lo, st, res) in vecs[:12]:
        key = ((hi << 32) | lo)
        print("  start=%2d key=%-20d -> %d" % (st, key, res))

if __name__ == "__main__":
    main()
