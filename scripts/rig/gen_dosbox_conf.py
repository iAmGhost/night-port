#!/usr/bin/env python3
"""Write the dosbox configs the rigs use.  Nothing here is committed, because a committed config is a
machine's address.

WHAT THIS REPLACES.  `scripts/rig/conf/*.conf` were tracked, and every one of them carried the same
absolute path -- this checkout's own location -- in `mount c`, `imgmount d` and `capto`.  So the harness
only worked on the one machine it was written on, and moving the disc (which happened) broke all four at
once.  A config that records where a machine keeps its files is not a config; it is a leak of one.

So the profiles live here, as text with no absolute path in it, and the paths are resolved when the
file is written: the repo root from this file, the game directory from the install set `make extract`
built, the disc from `scripts/disc_loc.py` (suffix, not name -- docs/455).  Override any of them for a
different tree:

    python3 scripts/rig/gen_dosbox_conf.py                       # -> scratch/rig/conf/*.conf
    python3 scripts/rig/gen_dosbox_conf.py --game-dir /mnt/rip/installed --cue /mnt/rip/GAME.CUE
    dosbox-staging --conf scratch/rig/conf/dosbox_snap.conf

C: is the install set, and it is also where the guest-side snapper puts its dumps (`C:\\CAP`, see
scripts/rig/snapper/snap.asm), so the directory has to be writable -- extracted/ is, and it is
git-ignored.  The snapper tools are mounted read-only as E: rather than copied into the game tree,
which is what made the old config assume the tools lived next to NIGHT.EXE.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "scripts"))
from disc_loc import find_cue, find_exe   # noqa: E402  (located by suffix, not by name)

SNAPPER = REPO / "scripts" / "rig" / "snapper"

HEADER = ("; generated by scripts/rig/gen_dosbox_conf.py -- do not edit, do not commit\n"
          "; root %s\n; game (C:) %s\n; cue (D:) %s\n")

# Everything below the [autoexec] line is the guest's boot script; the sections above it are the
# machine shape each profile was measured with, kept verbatim from the configs they replace.
PROFILES = {
    "dosbox_orig": {
        "body": """[dosbox]
machine=svga_s3
memsize=16

[cpu]
core=normal
cycles=auto

[mixer]
rate=44100
blocksize=1024
prebuffer=20

[sdl]
fullscreen=false
window_size=640x480
""",
        "autoexec": """echo === NIGHT original, captured for port comparison ===
mount c {game}
imgmount d {cue} -t iso -useimgmode none
capto {cap}
capm
c:
night
""",
    },
    "dosbox_playtest": {
        "body": """[dosbox]
machine = svga_s3
memsize = 16

[cpu]
core = normal
cycles = auto

[capture]
capture_dir = {cap}
default_image_capture_formats = raw

[sdl]
fullscreen = false
window_size = 640x480
""",
        "autoexec": """mount c {game}
imgmount d {cue} -t iso
c:
{autotype}
night
""",
    },
    "dosbox_snap": {
        "body": """[dosbox]
machine=svga_s3
memsize=16

[cpu]
core=normal
cycles=max

[mixer]
rate=44100
blocksize=1024
prebuffer=20

[sdl]
fullscreen=false
window_size=640x480
""",
        "autoexec": """mount c {game}
imgmount d {cue} -t iso -useimgmode none
mount e {snapper} -ro
c:
e:\\snap.com
night
""",
    },
    "dosbox_snapt": {
        "body": """[dosbox]
machine=svga_s3
memsize=16
[cpu]
core=normal
cycles=max
[mixer]
rate=44100
[sdl]
pause_when_lost_focus=false
fullscreen=false
""",
        "autoexec": """mount c {game}
mount e {snapper} -ro
c:
echo before > c:\\snaplog.txt
e:\\snap.com
echo after > c:\\snaplog.txt
mode co80
cls
dir c:\\cap
""",
    },
    "probe": {
        "body": """[sdl]
output=surface
pause_when_lost_focus=false
""",
        "autoexec": """echo HELLO > z:\\ZZZ.TXT
""",
    },
}

PACE = 0.5


def autotype_line(shots=None, wait: float = 3.0, pace: float = PACE) -> str:
    """The `autotype` line the playtest harness drives menus with (empty list = sit at the title)."""
    keys = shots if shots is not None else [","] * 24 + ["enter"]
    joined = " ".join(("enter" if k == "enter" else k) for k in keys)
    return f"autotype -w {wait:.1f} -p {pace:.1f} {joined}"


def conf_text(profile: str, *, root: Path | None = None, game: Path | None = None,
              cue: Path | None = None, cap: Path | None = None, snapper: Path | None = None,
              autotype: str = "") -> str:
    """One config's text, with every path resolved from the caller's context (never from a constant)."""
    if profile not in PROFILES:
        raise SystemExit(f"unknown profile {profile!r}: {', '.join(sorted(PROFILES))}")
    p = PROFILES[profile]
    root = Path(root) if root else REPO
    game = Path(game) if game else default_game()
    cap = Path(cap) if cap else root / "scratch" / "orig"
    vals = {"game": game, "cue": Path(cue) if cue else default_cue(), "cap": cap,
            "snapper": Path(snapper) if snapper else SNAPPER, "root": root,
            "autotype": autotype or autotype_line()}
    cap.mkdir(parents=True, exist_ok=True)
    head = "" if profile == "probe" else HEADER % (vals["root"], vals["game"], vals["cue"])
    body = p["body"].format(**{k: v for k, v in vals.items() if k != "autotype"})
    auto = p["autoexec"].format(**vals)
    return head + body + "\n[autoexec]\n" + auto


def default_game() -> Path:
    """The install set the game boots from -- the directory holding NIGHT.EXE (see scripts/disc_loc.py)."""
    exe = find_exe()
    if exe is None:
        raise SystemExit("no NIGHT.EXE found: run `make extract` (docs/455) or pass --game-dir DIR")
    return exe.resolve().parent


def default_cue() -> Path:
    cue = find_cue()
    if cue is None:
        raise SystemExit("no .cue found: pass --cue FILE (docs/455)")
    return cue.resolve()


def main() -> int:
    ap = argparse.ArgumentParser(description="write the dosbox rig configs with paths resolved here")
    ap.add_argument("-o", "--out", default=str(REPO / "scratch" / "rig" / "conf"),
                    help="where to write them (default: scratch/rig/conf -- git-ignored)")
    ap.add_argument("--root", default=None, help="repo root (default: derived from this script)")
    ap.add_argument("--game-dir", default=None, help="the install set to mount as C: (default: NIGHT.EXE's dir)")
    ap.add_argument("--cue", default=None, help="the CUE sheet to imgmount as D: (default: located)")
    ap.add_argument("--cap", default=None, help="capture dir (default: <root>/scratch/orig)")
    ap.add_argument("--snapper", default=None, help="dir holding snap.com (default: scripts/rig/snapper)")
    ap.add_argument("--profiles", default=",".join(PROFILES), help="comma-separated subset to write")
    ap.add_argument("--print", dest="show", action="store_true", help="print instead of writing")
    a = ap.parse_args()

    out = Path(a.out)
    if not a.show:
        out.mkdir(parents=True, exist_ok=True)
    for name in [p.strip() for p in a.profiles.split(",") if p.strip()]:
        text = conf_text(name, root=a.root, game=a.game_dir, cue=a.cue, cap=a.cap, snapper=a.snapper)
        if a.show:
            print(f"########## {name}\n{text}")
            continue
        path = out / f"{name}.conf"
        path.write_text(text)
        print(f"wrote {path}")
    if not a.show:
        print(f"\nrun it, e.g.:  dosbox-staging --conf {out / 'dosbox_snap.conf'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
